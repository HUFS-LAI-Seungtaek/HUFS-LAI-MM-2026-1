def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--count", type=int, default=20)
    parser.add_argument("--skip-api", action="store_true", help="Only download sample images and make a placeholder HTML.")
    args = parser.parse_args()

    load_env_file(OUTPUT_DIR / ".env")
    api_key = os.getenv("OPENROUTER_API_KEY")

    samples = save_sample_images(args.count)
    existing_results = load_existing_results()
    results = []

    if args.skip_api:
        for sample in samples:
            results.append(
                {
                    **sample,
                    "has_human": "no",
                    "has_animal": "no",
                    "has_flower": "no",
                    "looks_ai_generated": "no",
                    "reason": "Placeholder only. Run without --skip-api to classify this image.",
                    "ai_reason": "Placeholder only. Run without --skip-api to judge AI-like visual characteristics.",
                }
            )
    else:
        if not api_key:
            raise RuntimeError("OPENROUTER_API_KEY is missing. Create .env with OPENROUTER_API_KEY=your_token")
        for sample in samples:
            sample_id = sample["sample_id"]
            if sample_id in existing_results and existing_results[sample_id].get("status") not in {
                "skipped",
                "skipped_error",
                "skipped_empty_content",
            }:
                print(f"Using existing result for sample {sample_id}/{len(samples)}")
                results.append(existing_results[sample_id])
                continue

            print(f"Classifying sample {sample_id}/{len(samples)}")
            try:
                results.append(classify_image(api_key, sample))
            except KeyboardInterrupt:
                print("Interrupted. Saving partial results before exiting.")
                break
            except Exception as exc:
                print(f"Skipping sample {sample_id} after error: {exc}")
                results.append(skipped_result(sample, f"Skipped because classification failed: {exc}", "skipped_error"))
            RESULTS_JSON.write_text(json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8")
            RESULTS_HTML.write_text(render_html(results), encoding="utf-8")
            time.sleep(1)

    RESULTS_JSON.write_text(json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8")
    RESULTS_HTML.write_text(render_html(results), encoding="utf-8")
    print(f"Wrote {RESULTS_HTML}")


if __name__ == "__main__":
    main()
