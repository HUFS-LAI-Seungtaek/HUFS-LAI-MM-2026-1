import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path


MODEL = "nvidia/nemotron-3-nano-omni-30b-a3b-reasoning:free"
FALLBACK_MODELS = ["google/gemini-2.0-flash-exp:free"]
DATASET_ROWS_URL = "https://datasets-server.huggingface.co/rows"
DATASET_PARAMS = {
    "dataset": "huggan/wikiart",
    "config": "default",
    "split": "train",
    "offset": 0,
}
OUTPUT_DIR = Path(__file__).resolve().parent
IMAGE_DIR = OUTPUT_DIR / "images"
RESULTS_JSON = OUTPUT_DIR / "results.json"
RESULTS_HTML = OUTPUT_DIR / "results.html"
REQUEST_TIMEOUT_SECONDS = 45


CLASSIFICATION_SCHEMA = {
    "name": "wikiart_image_classification",
    "strict": True,
    "schema": {
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "has_human": {"type": "string", "enum": ["yes", "no"]},
            "has_animal": {"type": "string", "enum": ["yes", "no"]},
            "has_flower": {"type": "string", "enum": ["yes", "no"]},
            "looks_ai_generated": {"type": "string", "enum": ["yes", "no"]},
            "reason": {
                "type": "string",
                "description": "A short natural-language explanation with visual evidence and location words when possible.",
            },
            "ai_reason": {
                "type": "string",
                "description": "A short explanation of why the artwork looks AI-generated or clearly human-made.",
            },
        },
        "required": ["has_human", "has_animal", "has_flower", "looks_ai_generated", "reason", "ai_reason"],
    },
}


SYSTEM_PROMPT = """You classify WikiArt images using a fixed schema.

Definitions:
- has_human: "yes" if any human figure, face, body part, portrait, statue-like human, or clearly human silhouette is visible. Otherwise "no".
- has_animal: "yes" if any non-human animal, bird, fish, insect, horse, dog, mythical animal-like creature, or animal body part is visible. Otherwise "no".
- has_flower: "yes" if any flower blossom, bouquet, flowering plant, or clearly decorative floral motif is visible. Leaves alone are not enough. Otherwise "no".
- looks_ai_generated: Judge whether this artwork looks like it could have been generated by an AI image model (like Midjourney or DALL-E), based on visual characteristics such as texture consistency, anatomical accuracy, lighting uniformity, or surreal elements. Note: all images are actually historical human artworks.

Write a brief reason in English. Mention visual evidence and location words such as center, top-left, foreground, background, or right side when possible.
Keep reason and ai_reason under 25 words each.
For ai_reason, briefly explain why the image looks AI-generated or clearly human-made.
Return only the JSON object matching the schema."""


def encode_image_as_data_url(image_path: Path, mime_type: str | None = None) -> str:
    mime = mime_type or mimetypes.guess_type(image_path.name)[0] or "image/jpeg"
    encoded = base64.b64encode(image_path.read_bytes()).decode("utf-8")
    return f"data:{mime};base64,{encoded}"


def load_env_file(path: Path) -> None:
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, value = stripped.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def request_json(
    url: str,
    method: str = "GET",
    payload: dict | None = None,
    headers: dict | None = None,
    timeout: int = REQUEST_TIMEOUT_SECONDS,
) -> dict:
    data = None
    request_headers = headers or {}
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        request_headers = {"Content-Type": "application/json", **request_headers}
    request = urllib.request.Request(url, data=data, headers=request_headers, method=method)
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"HTTP {exc.code} from {url}: {detail}") from exc
    except (TimeoutError, socket.timeout, urllib.error.URLError) as exc:
        raise RuntimeError(f"Request failed or timed out after {timeout}s for {url}: {exc}") from exc


def download_bytes(url: str) -> tuple[bytes, str]:
    request = urllib.request.Request(url, headers={"User-Agent": "assignment2-wikiart-classifier/1.0"})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            content_type = response.headers.get("Content-Type", "image/jpeg").split(";")[0]
            return response.read(), content_type
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"HTTP {exc.code} while downloading image: {detail}") from exc


def find_image_url(value) -> str | None:
    if isinstance(value, dict):
        src = value.get("src")
        if isinstance(src, str) and src.startswith("http"):
            return src
        for nested in value.values():
            found = find_image_url(nested)
            if found:
                return found
    if isinstance(value, list):
        for nested in value:
            found = find_image_url(nested)
            if found:
                return found
    return None


def image_extension(content_type: str) -> str:
    if "png" in content_type:
        return ".png"
    if "webp" in content_type:
        return ".webp"
    return ".jpg"


def normalize_image_mime_type(content_type: str, image_url: str) -> str:
    guessed = mimetypes.guess_type(urllib.parse.urlparse(image_url).path)[0]
    if content_type.startswith("image/"):
        return content_type
    return guessed or "image/jpeg"


def fetch_dataset_rows(count: int) -> list[dict]:
    params = {**DATASET_PARAMS, "length": count}
    url = f"{DATASET_ROWS_URL}?{urllib.parse.urlencode(params, quote_via=urllib.parse.quote, safe='/')}"
    payload = request_json(url)
    rows = payload.get("rows", [])
    if not rows:
        raise RuntimeError("No rows returned from the Hugging Face datasets HTTP API.")
    return rows


def save_sample_images(count: int) -> list[dict]:
    IMAGE_DIR.mkdir(parents=True, exist_ok=True)
    rows = fetch_dataset_rows(count)
    samples = []
    for sample_number, item in enumerate(rows, start=1):
        row = item.get("row", item)
        image_url = find_image_url(row)
        if not image_url:
            raise RuntimeError(f"Could not find an image URL in row {sample_number}.")

        image_content, raw_mime_type = download_bytes(image_url)
        mime_type = normalize_image_mime_type(raw_mime_type, image_url)
        image_name = f"wikiart_{sample_number:03d}{image_extension(mime_type)}"
        image_path = IMAGE_DIR / image_name
        image_path.write_bytes(image_content)
        samples.append(
            {
                "sample_id": sample_number,
                "dataset_index": item.get("row_idx", sample_number - 1),
                "image_file": f"images/{image_name}",
                "image_url": image_url,
                "mime_type": mime_type,
            }
        )
    return samples


def parse_classification_response(response_payload: dict, sample: dict) -> dict:
    content = response_payload["choices"][0]["message"].get("content")
    if content is None:
        print("Raw API response with empty content:")
        print(json.dumps(response_payload, indent=2, ensure_ascii=False))
        raise ValueError("API response content was empty")
    parsed = content if isinstance(content, dict) else json.loads(content)
    return {**sample, **parsed}


def build_payload(sample: dict, model: str) -> dict:
    image_path = OUTPUT_DIR / sample["image_file"]
    prompt_text = "Classify this WikiArt image for human, animal, flower, and AI-generated appearance."
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {
                "role": "user",
                "content": [
                    {
                        "type": "text",
                        "text": prompt_text,
                    },
                    {
                        "type": "image_url",
                        "image_url": {"url": encode_image_as_data_url(image_path, sample.get("mime_type"))},
                    },
                ],
            },
        ],
        "response_format": {
            "type": "json_schema",
            "json_schema": CLASSIFICATION_SCHEMA,
        },
        "provider": {
            "require_parameters": True,
        },
        "temperature": 0,
        "max_tokens": 300,
    }
    return payload


def classify_image(api_key: str, sample: dict) -> dict:
    last_error = None
    models = [MODEL, *FALLBACK_MODELS]
    for model in models:
        try:
            response_payload = request_json(
                "https://openrouter.ai/api/v1/chat/completions",
                method="POST",
                headers={
                    "Authorization": f"Bearer {api_key}",
                    "HTTP-Referer": "https://github.com/",
                    "X-Title": "Assignment 2 Schema-Guided WikiArt Classification",
                },
                payload=build_payload(sample, model),
            )
            result = parse_classification_response(response_payload, sample)
            result["model_used"] = model
            if model != MODEL:
                result["status"] = "ok_after_model_fallback"
            return result
        except Exception as exc:
            last_error = exc
            print(f"{model} schema-guided attempt failed for sample {sample['sample_id']}: {exc}")
        if model != models[-1]:
            time.sleep(2)
    raise RuntimeError(f"All schema-guided classification attempts failed: {last_error}") from last_error


def skipped_result(sample: dict, reason: str, status: str = "skipped") -> dict:
    return {
        **sample,
        "has_human": "no",
        "has_animal": "no",
        "has_flower": "no",
        "looks_ai_generated": "no",
        "reason": reason,
        "ai_reason": reason,
        "status": status,
    }


def load_existing_results() -> dict[int, dict]:
    if not RESULTS_JSON.exists():
        return {}
    try:
        results = json.loads(RESULTS_JSON.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}
    return {
        int(item["sample_id"]): item
        for item in results
        if isinstance(item, dict) and "sample_id" in item
    }


